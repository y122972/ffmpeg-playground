/** 全部页：按分组 + 常用度排序 */
export function groupedAll(): { id: ParamGroup; label: string; hint?: string; items: Def[] }[] {
  return GROUP_META.map((g) => ({
    ...g,
    items: DEFS.filter((d) => d.group === g.id).sort((a, b) => a.rank - b.rank),
  })).filter((g) => g.items.length > 0);
}
